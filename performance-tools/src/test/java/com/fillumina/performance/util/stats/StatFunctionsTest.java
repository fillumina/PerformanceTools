    public static double orig(double q, double i, double j, double b) {
        double zz = 1;
        double z = 1;
        double k = i;
        while (k <= j) {
            zz *= q * k / (k - b);
            z += zz;
            k += 2;
        }
        return z;
    }

    public static double modi(double q, double i, double j, double b) {
        double zz = 1.0;
        double z = 1.0;
        int k = (int)i;
        int jj = (int)j;
        while (k <= jj) {
            zz *= q * k / (k - b);
            z += zz;
            k += 2.0;
        }
        return z;
    }

    public static double modi_old1(double q, double i, double j, double b) {
        double zz = 1.0;
        double z = 1.0;
        int k = (int)i;
        int jj = (int)j;
        int bb = (int)b;
        while (k <= jj) {
            zz *= q * k / (k - bb);
            z += zz;
            k += 2;
        }
        return z;
    }

